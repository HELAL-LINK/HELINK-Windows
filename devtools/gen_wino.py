#!/usr/bin/env python3
"""Writes mdxwino_amd64.s: the Winograd F(4x4, 3x3) transforms of the voice network's
3x3 convolutions (mdxwino.go), with AVX2 and FMA, 8 tiles at a time.

    python3 devtools/gen_wino.py > mdxwino_amd64.s

winoInAVX2(src, rs, dst, xs, tmp, pf): src is row 0 of the 6 input rows of 8 tiles, at
the column 4 before the first tile's first input (40 floats are read per row, 3..36 used);
rs is the row stride in bytes. The 36 values V = Bt d B of each tile go to
dst + xi*xs (8 floats: the 8 tiles), xi = 6i + j. tmp: 36 vectors of scratch. pf: the
same rows of the channel to come, asked from memory now (the channels are far apart).

winoOutAVX2(src, xs, bias, dst, rs, tmp): src + xi*xs holds M[xi] for 8 tiles; the 4x4
outputs Y = At M A of each, plus the bias, ReLU, go to dst (4 rows of 32 floats, row
stride rs bytes), past the caches (dst 32-byte aligned; winoFence before they are read).
tmp: 40 vectors of scratch.

winoGemmAVX2(cin, u, uxs, v, vrs, m, mrs, nb): for each of the 36 and each 16 of the nb
tiles, the 6 output channels' sums over the input channels: M[xi] = U[xi] V[xi], U
packed as for convTile (u + xi*uxs), V rows at v + ci*vrs + xi*nb*4, M rows at
m + co*mrs + xi*nb*4.
"""

out = []


def e(s):
    out.append('\t' + s)


def label(s):
    out.append(s + ':')


def y(i):
    return 'Y%d' % i


# Constants: 2, 4, 5, 8, and the lane rotations for vpermps.
HEAD = '''#include "textflag.h"

// Generated by devtools/gen_wino.py: the Winograd F(4x4, 3x3) transforms (see mdxwino.go).

DATA winoC<>+0(SB)/4, $2.0
DATA winoC<>+4(SB)/4, $4.0
DATA winoC<>+8(SB)/4, $5.0
DATA winoC<>+12(SB)/4, $8.0
GLOBL winoC<>(SB), RODATA|NOPTR, $16

// [7 0 1 2 3 4 5 6]: lanes moved up by one; [1 2 3 4 5 6 7 0]: down by one.
DATA winoUp<>+0(SB)/4, $7
DATA winoUp<>+4(SB)/4, $0
DATA winoUp<>+8(SB)/4, $1
DATA winoUp<>+12(SB)/4, $2
DATA winoUp<>+16(SB)/4, $3
DATA winoUp<>+20(SB)/4, $4
DATA winoUp<>+24(SB)/4, $5
DATA winoUp<>+28(SB)/4, $6
GLOBL winoUp<>(SB), RODATA|NOPTR, $32
DATA winoDown<>+0(SB)/4, $1
DATA winoDown<>+4(SB)/4, $2
DATA winoDown<>+8(SB)/4, $3
DATA winoDown<>+12(SB)/4, $4
DATA winoDown<>+16(SB)/4, $5
DATA winoDown<>+20(SB)/4, $6
DATA winoDown<>+24(SB)/4, $7
DATA winoDown<>+28(SB)/4, $0
GLOBL winoDown<>(SB), RODATA|NOPTR, $32
'''


def bt(x, store, tmp, c4, c5):
    """t = Bt x for x = 6 registers; store(k, reg) writes t_k. tmp: 4 free registers."""
    a, b, c, d = tmp
    # t1 = (x4 - 4x2) - (4x1 - x3), t2 = (x4 - 4x2) + (4x1 - x3)
    e('VMOVAPS %s, %s' % (x[4], a))
    e('VFNMADD231PS %s, %s, %s' % (x[2], c4, a))
    e('VMOVAPS %s, %s' % (x[3], b))
    e('VFMSUB231PS %s, %s, %s' % (x[1], c4, b))
    e('VSUBPS %s, %s, %s' % (b, a, c))
    store(1, c)
    e('VADDPS %s, %s, %s' % (b, a, c))
    store(2, c)
    # t3 = (x4 - x2) - 2(x1 - x3), t4 = (x4 - x2) + 2(x1 - x3)
    e('VSUBPS %s, %s, %s' % (x[2], x[4], a))
    e('VSUBPS %s, %s, %s' % (x[3], x[1], b))
    e('VADDPS %s, %s, %s' % (b, b, b))
    e('VSUBPS %s, %s, %s' % (b, a, c))
    store(3, c)
    e('VADDPS %s, %s, %s' % (b, a, c))
    store(4, c)
    # t0 = 4x0 - 5x2 + x4, t5 = 4x1 - 5x3 + x5
    e('VMOVAPS %s, %s' % (x[4], a))
    e('VFNMADD231PS %s, %s, %s' % (x[2], c5, a))
    e('VFMADD231PS %s, %s, %s' % (x[0], c4, a))
    store(0, a)
    e('VMOVAPS %s, %s' % (x[5], d))
    e('VFNMADD231PS %s, %s, %s' % (x[3], c5, d))
    e('VFMADD231PS %s, %s, %s' % (x[1], c4, d))
    store(5, d)


def at(m, store, tmp, c2, c4, c8):
    """y = At m for m = 6 registers (overwritten); store(k, reg) writes y_k."""
    p, q, r, s = tmp
    e('VADDPS %s, %s, %s' % (m[2], m[1], p))
    e('VSUBPS %s, %s, %s' % (m[2], m[1], q))
    e('VADDPS %s, %s, %s' % (m[4], m[3], r))
    e('VSUBPS %s, %s, %s' % (m[4], m[3], s))
    # y0 = m0 + p + r
    e('VADDPS %s, %s, %s' % (p, m[0], m[0]))
    e('VADDPS %s, %s, %s' % (r, m[0], m[0]))
    store(0, m[0])
    # y1 = q + 2s
    e('VMOVAPS %s, %s' % (q, m[1]))
    e('VFMADD231PS %s, %s, %s' % (s, c2, m[1]))
    store(1, m[1])
    # y2 = p + 4r
    e('VFMADD231PS %s, %s, %s' % (r, c4, p))
    store(2, p)
    # y3 = q + 8s + m5
    e('VADDPS %s, %s, %s' % (m[5], q, q))
    e('VFMADD231PS %s, %s, %s' % (s, c8, q))
    store(3, q)


def wino_in():
    e = globals()['e']
    out.append('')
    out.append('// func winoInAVX2(src *float32, rs int, dst *float32, xs int, tmp *float32, pf *float32)')
    out.append('TEXT ·winoInAVX2(SB), NOSPLIT, $0-48')
    e('MOVQ src+0(FP), SI')
    e('MOVQ rs+8(FP), DX')
    e('MOVQ dst+16(FP), DI')
    e('MOVQ xs+24(FP), BX')
    e('MOVQ tmp+32(FP), R8')
    e('MOVQ pf+40(FP), R9')
    for r in range(6):
        for off in (0, 64, 128):
            e('PREFETCHT0 %d(R9)' % off)
        if r < 5:
            e('ADDQ DX, R9')
    e('LEAQ winoC<>(SB), AX')
    e('VBROADCASTSS 4(AX), Y14')  # 4
    e('VBROADCASTSS 8(AX), Y15')  # 5
    for r in range(6):
        # Columns 4..35 of the window: four vectors, split into the 4 phases.
        for k in range(4):
            e('VMOVUPS %d(SI), %s' % (16 + 32 * k, y(k)))
        e('VPERM2F128 $0x20, Y2, Y0, Y4')
        e('VPERM2F128 $0x31, Y2, Y0, Y5')
        e('VPERM2F128 $0x20, Y3, Y1, Y6')
        e('VPERM2F128 $0x31, Y3, Y1, Y7')
        e('VUNPCKLPS Y5, Y4, Y0')
        e('VUNPCKHPS Y5, Y4, Y1')
        e('VUNPCKLPS Y7, Y6, Y2')
        e('VUNPCKHPS Y7, Y6, Y3')
        e('VUNPCKLPD Y2, Y0, Y5')   # phase 0: x1 (columns 4m+4)
        e('VUNPCKHPD Y2, Y0, Y6')   # phase 1: x2
        e('VUNPCKLPD Y3, Y1, Y7')   # phase 2: x3
        e('VUNPCKHPD Y3, Y1, Y8')   # phase 3: x4
        # x0 = columns 4m+3: x4 one lane up, column 3 in lane 0.
        e('LEAQ winoUp<>(SB), AX')
        e('VMOVUPS (AX), Y9')
        e('VPERMPS Y8, Y9, Y4')
        e('VBROADCASTSS 12(SI), Y9')
        e('VBLENDPS $0x01, Y9, Y4, Y4')
        # x5 = columns 4m+8: x1 one lane down, column 36 in lane 7.
        e('LEAQ winoDown<>(SB), AX')
        e('VMOVUPS (AX), Y9')
        e('VPERMPS Y5, Y9, Y0')
        e('VBROADCASTSS 144(SI), Y9')
        e('VBLENDPS $0x80, Y9, Y0, Y0')
        x = ['Y4', 'Y5', 'Y6', 'Y7', 'Y8', 'Y0']
        bt(x, lambda k, reg, r=r: e('VMOVUPS %s, %d(R8)' % (reg, 32 * (6 * r + k))), ['Y1', 'Y2', 'Y3', 'Y9'], 'Y14', 'Y15')
        if r < 5:
            e('ADDQ DX, SI')
    # Down the rows: V[6i+j] = (Bt T)[i][j], T[r][j] in tmp.
    for j in range(6):
        for r in range(6):
            e('VMOVUPS %d(R8), %s' % (32 * (6 * r + j), y(r)))

        def st(i, reg, j=j):
            # dst + (6i+j)*xs
            e('MOVQ $%d, AX' % (6 * i + j))
            e('IMULQ BX, AX')
            e('VMOVUPS %s, (DI)(AX*1)' % reg)
        bt([y(k) for k in range(6)], st, ['Y6', 'Y7', 'Y8', 'Y9'], 'Y14', 'Y15')
    e('VZEROUPPER')
    e('RET')


def wino_out():
    out.append('')
    out.append('// func winoOutAVX2(src *float32, xs int, bias *float32, dst *float32, rs int, tmp *float32)')
    out.append('TEXT ·winoOutAVX2(SB), NOSPLIT, $0-48')
    e('MOVQ src+0(FP), SI')
    e('MOVQ xs+8(FP), BX')
    e('MOVQ bias+16(FP), CX')
    e('MOVQ dst+24(FP), DI')
    e('MOVQ rs+32(FP), DX')
    e('MOVQ tmp+40(FP), R8')
    e('LEAQ winoC<>(SB), AX')
    e('VBROADCASTSS 0(AX), Y13')  # 2
    e('VBROADCASTSS 4(AX), Y14')  # 4
    e('VBROADCASTSS 12(AX), Y15')  # 8
    # Along j: R[i][b] = (At M[i][.])[b], into tmp[4i+b].
    for i in range(6):
        for j in range(6):
            e('MOVQ $%d, AX' % (6 * i + j))
            e('IMULQ BX, AX')
            e('VMOVUPS (SI)(AX*1), %s' % y(j))
        at([y(k) for k in range(6)], lambda b, reg, i=i: e('VMOVUPS %s, %d(R8)' % (reg, 32 * (4 * i + b))),
           ['Y6', 'Y7', 'Y8', 'Y9'], 'Y13', 'Y14', 'Y15')
    # Along i: Y[a][b] = (At R[.][b])[a], into tmp[24 + 4a + b].
    for b in range(4):
        for i in range(6):
            e('VMOVUPS %d(R8), %s' % (32 * (4 * i + b), y(i)))
        at([y(k) for k in range(6)], lambda a, reg, b=b: e('VMOVUPS %s, %d(R8)' % (reg, 32 * (24 + 4 * a + b))),
           ['Y6', 'Y7', 'Y8', 'Y9'], 'Y13', 'Y14', 'Y15')
    # Each output row: plus the bias, ReLU, the 4 phases interleaved into 32 columns.
    e('VBROADCASTSS (CX), Y12')
    e('VXORPS Y11, Y11, Y11')
    for a in range(4):
        for b in range(4):
            e('VMOVUPS %d(R8), %s' % (32 * (24 + 4 * a + b), y(b)))
            e('VADDPS Y12, %s, %s' % (y(b), y(b)))
            e('VMAXPS Y11, %s, %s' % (y(b), y(b)))
        e('VUNPCKLPS Y1, Y0, Y4')
        e('VUNPCKHPS Y1, Y0, Y5')
        e('VUNPCKLPS Y3, Y2, Y6')
        e('VUNPCKHPS Y3, Y2, Y7')
        e('VUNPCKLPD Y6, Y4, Y0')   # columns 0-3 | 16-19
        e('VUNPCKHPD Y6, Y4, Y1')   # 4-7 | 20-23
        e('VUNPCKLPD Y7, Y5, Y2')   # 8-11 | 24-27
        e('VUNPCKHPD Y7, Y5, Y3')   # 12-15 | 28-31
        e('VPERM2F128 $0x20, Y1, Y0, Y4')
        e('VPERM2F128 $0x20, Y3, Y2, Y5')
        e('VPERM2F128 $0x31, Y1, Y0, Y6')
        e('VPERM2F128 $0x31, Y3, Y2, Y7')
        e('VMOVNTPS Y4, 0(DI)')
        e('VMOVNTPS Y5, 32(DI)')
        e('VMOVNTPS Y6, 64(DI)')
        e('VMOVNTPS Y7, 96(DI)')
        if a < 3:
            e('ADDQ DX, DI')
    e('VZEROUPPER')
    e('RET')
    out.append('')
    out.append('// func winoFence(): the streaming stores of winoOutAVX2 done before what follows.')
    out.append('TEXT ·winoFence(SB), NOSPLIT, $0-0')
    e('SFENCE')
    e('RET')


def wino_gemm():
    out.append('')
    out.append('// func winoGemmAVX2(cin int, u *float32, uxs int, v *float32, vrs int, m *float32, mrs int, nb int)')
    out.append('TEXT ·winoGemmAVX2(SB), NOSPLIT, $0-64')
    e('MOVQ cin+0(FP), CX')
    e('MOVQ u+8(FP), R8')       # U[xi], moved on by uxs
    e('MOVQ uxs+16(FP), R9')
    e('MOVQ v+24(FP), R10')     # V[xi] for the tiles j
    e('MOVQ vrs+32(FP), R11')
    e('MOVQ m+40(FP), R12')     # M[xi] for the tiles j
    e('MOVQ mrs+48(FP), R13')
    e('MOVQ nb+56(FP), DX')
    e('SHLQ $2, DX')            # nb*4: bytes between the 36
    e('MOVQ $36, BX')
    label('xloop')
    e('XORQ DI, DI')            # byte offset of the tiles j within V[xi], M[xi]
    label('jloop')
    for i in range(12):
        e('VXORPS %s, %s, %s' % (y(i), y(i), y(i)))
    e('MOVQ R8, SI')
    e('LEAQ (R10)(DI*1), AX')
    e('MOVQ CX, R14')
    label('kloop')
    e('VMOVUPS (AX), Y12')
    e('VMOVUPS 32(AX), Y13')
    for i in range(6):
        b = 'Y14' if i % 2 == 0 else 'Y15'
        e('VBROADCASTSS %d(SI), %s' % (4 * i, b))
        e('VFMADD231PS Y12, %s, %s' % (b, y(2 * i)))
        e('VFMADD231PS Y13, %s, %s' % (b, y(2 * i + 1)))
    e('ADDQ $24, SI')
    e('ADDQ R11, AX')
    e('DECQ R14')
    e('JNZ kloop')
    e('LEAQ (R12)(DI*1), AX')
    for i in range(6):
        e('VMOVUPS %s, (AX)' % y(2 * i))
        e('VMOVUPS %s, 32(AX)' % y(2 * i + 1))
        if i < 5:
            e('ADDQ R13, AX')
    e('ADDQ $64, DI')
    e('CMPQ DI, DX')
    e('JLT jloop')
    e('ADDQ R9, R8')
    e('ADDQ DX, R10')
    e('ADDQ DX, R12')
    e('DECQ BX')
    e('JNZ xloop')
    e('VZEROUPPER')
    e('RET')


print(HEAD, end='')
wino_in()
wino_out()
wino_gemm()
print('\n'.join(out))
