	TESTQ $4, R11
	JZ    rnoadd
	MOVQ 96(R9), R10
	VADDPS (R10), Y0, Y0
	VADDPS 32(R10), Y1, Y1
	MOVQ 104(R9), R10
	VADDPS (R10), Y2, Y2
	VADDPS 32(R10), Y3, Y3
	MOVQ 112(R9), R10
	VADDPS (R10), Y4, Y4
	VADDPS 32(R10), Y5, Y5
	MOVQ 120(R9), R10
	VADDPS (R10), Y6, Y6
	VADDPS 32(R10), Y7, Y7
	MOVQ 128(R9), R10
	VADDPS (R10), Y8, Y8
	VADDPS 32(R10), Y9, Y9
	MOVQ 136(R9), R10
	VADDPS (R10), Y10, Y10
	VADDPS 32(R10), Y11, Y11

