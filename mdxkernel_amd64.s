#include "textflag.h"

// The two inner loops of the voice network (mdxkernel.go), with AVX2 and FMA: each makes
// one tile of 6 rows by 16 columns of a matrix product, keeping the 96 sums in 12
// registers, then finishes it (scale and bias for each row, the ReLU, multiplied by or
// added to other rows: the tileEp flags) and writes the 6 rows where tileEp says.
//
// tileEp: scale [6]float32 at 0, bias [6]float32 at 24, orow [6]unsafe.Pointer at 48,
// drow [6]unsafe.Pointer at 96, flags at 144 (1 ReLU, 2 multiply by drow, 4 add drow).

// func convTileAVX2(k int, panel, base *float32, offs *int, ep *tileEp)
// sum[i][j] = Σ_p panel[6p+i] * row_p[j], row_p = base + offs[p] bytes (16 floats each).
TEXT ·convTileAVX2(SB), NOSPLIT, $0-40
	MOVQ k+0(FP), CX
	MOVQ panel+8(FP), SI
	MOVQ base+16(FP), DX
	MOVQ offs+24(FP), BX
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	TESTQ CX, CX
	JLE   cdone

cloop:
	MOVQ (BX), AX
	VMOVUPS (DX)(AX*1), Y12
	VMOVUPS 32(DX)(AX*1), Y13
	VBROADCASTSS 0(SI), Y14
	VFMADD231PS Y12, Y14, Y0
	VFMADD231PS Y13, Y14, Y1
	VBROADCASTSS 4(SI), Y15
	VFMADD231PS Y12, Y15, Y2
	VFMADD231PS Y13, Y15, Y3
	VBROADCASTSS 8(SI), Y14
	VFMADD231PS Y12, Y14, Y4
	VFMADD231PS Y13, Y14, Y5
	VBROADCASTSS 12(SI), Y15
	VFMADD231PS Y12, Y15, Y6
	VFMADD231PS Y13, Y15, Y7
	VBROADCASTSS 16(SI), Y14
	VFMADD231PS Y12, Y14, Y8
	VFMADD231PS Y13, Y14, Y9
	VBROADCASTSS 20(SI), Y15
	VFMADD231PS Y12, Y15, Y10
	VFMADD231PS Y13, Y15, Y11
	ADDQ $24, SI
	ADDQ $8, BX
	DECQ CX
	JNZ  cloop

cdone:
	MOVQ ep+32(FP), R9
	MOVQ 144(R9), R11

	VBROADCASTSS 0(R9), Y12
	VBROADCASTSS 24(R9), Y13
	VFMADD213PS Y13, Y12, Y0
	VFMADD213PS Y13, Y12, Y1
	VBROADCASTSS 4(R9), Y12
	VBROADCASTSS 28(R9), Y13
	VFMADD213PS Y13, Y12, Y2
	VFMADD213PS Y13, Y12, Y3
	VBROADCASTSS 8(R9), Y12
	VBROADCASTSS 32(R9), Y13
	VFMADD213PS Y13, Y12, Y4
	VFMADD213PS Y13, Y12, Y5
	VBROADCASTSS 12(R9), Y12
	VBROADCASTSS 36(R9), Y13
	VFMADD213PS Y13, Y12, Y6
	VFMADD213PS Y13, Y12, Y7
	VBROADCASTSS 16(R9), Y12
	VBROADCASTSS 40(R9), Y13
	VFMADD213PS Y13, Y12, Y8
	VFMADD213PS Y13, Y12, Y9
	VBROADCASTSS 20(R9), Y12
	VBROADCASTSS 44(R9), Y13
	VFMADD213PS Y13, Y12, Y10
	VFMADD213PS Y13, Y12, Y11

	TESTQ $1, R11
	JZ    cnorelu
	VXORPS Y15, Y15, Y15
	VMAXPS Y15, Y0, Y0
	VMAXPS Y15, Y1, Y1
	VMAXPS Y15, Y2, Y2
	VMAXPS Y15, Y3, Y3
	VMAXPS Y15, Y4, Y4
	VMAXPS Y15, Y5, Y5
	VMAXPS Y15, Y6, Y6
	VMAXPS Y15, Y7, Y7
	VMAXPS Y15, Y8, Y8
	VMAXPS Y15, Y9, Y9
	VMAXPS Y15, Y10, Y10
	VMAXPS Y15, Y11, Y11

cnorelu:
	TESTQ $2, R11
	JZ    cnomul
	MOVQ 96(R9), R10
	VMULPS (R10), Y0, Y0
	VMULPS 32(R10), Y1, Y1
	MOVQ 104(R9), R10
	VMULPS (R10), Y2, Y2
	VMULPS 32(R10), Y3, Y3
	MOVQ 112(R9), R10
	VMULPS (R10), Y4, Y4
	VMULPS 32(R10), Y5, Y5
	MOVQ 120(R9), R10
	VMULPS (R10), Y6, Y6
	VMULPS 32(R10), Y7, Y7
	MOVQ 128(R9), R10
	VMULPS (R10), Y8, Y8
	VMULPS 32(R10), Y9, Y9
	MOVQ 136(R9), R10
	VMULPS (R10), Y10, Y10
	VMULPS 32(R10), Y11, Y11

cnomul:
	TESTQ $4, R11
	JZ    cnoadd
	MOVQ 96(R9), R10
	VADDPS (R10), Y0, Y0
	VADDPS 32(R10), Y1, Y1
	MOVQ 104(R9), R10
	VADDPS (R10), Y2, Y2
	VADDPS 32(R10), Y3, Y3
	MOVQ 112(R9), R10
	VADDPS (R10), Y4, Y4
	VADDPS 32(R10), Y5, Y5
	MOVQ 120(R9), R10
	VADDPS (R10), Y6, Y6
	VADDPS 32(R10), Y7, Y7
	MOVQ 128(R9), R10
	VADDPS (R10), Y8, Y8
	VADDPS 32(R10), Y9, Y9
	MOVQ 136(R9), R10
	VADDPS (R10), Y10, Y10
	VADDPS 32(R10), Y11, Y11

cnoadd:
	MOVQ 48(R9), R10
	VMOVUPS Y0, (R10)
	VMOVUPS Y1, 32(R10)
	MOVQ 56(R9), R10
	VMOVUPS Y2, (R10)
	VMOVUPS Y3, 32(R10)
	MOVQ 64(R9), R10
	VMOVUPS Y4, (R10)
	VMOVUPS Y5, 32(R10)
	MOVQ 72(R9), R10
	VMOVUPS Y6, (R10)
	VMOVUPS Y7, 32(R10)
	MOVQ 80(R9), R10
	VMOVUPS Y8, (R10)
	VMOVUPS Y9, 32(R10)
	MOVQ 88(R9), R10
	VMOVUPS Y10, (R10)
	VMOVUPS Y11, 32(R10)
	VZEROUPPER
	RET

// func rowsTileAVX2(k int, rows *[6]unsafe.Pointer, panel *float32, ep *tileEp)
// sum[i][j] = Σ_p rows[i][p] * panel[16p+j]: 6 rows of a matrix (k floats each, anywhere)
// times a packed panel of 16 columns.
TEXT ·rowsTileAVX2(SB), NOSPLIT, $0-32
	MOVQ k+0(FP), CX
	MOVQ rows+8(FP), AX
	MOVQ panel+16(FP), SI
	MOVQ 0(AX), R8
	MOVQ 8(AX), R10
	MOVQ 16(AX), R12
	MOVQ 24(AX), R13
	MOVQ 32(AX), DI
	MOVQ 40(AX), DX
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
	VXORPS Y4, Y4, Y4
	VXORPS Y5, Y5, Y5
	VXORPS Y6, Y6, Y6
	VXORPS Y7, Y7, Y7
	VXORPS Y8, Y8, Y8
	VXORPS Y9, Y9, Y9
	VXORPS Y10, Y10, Y10
	VXORPS Y11, Y11, Y11
	XORQ  BX, BX
	TESTQ CX, CX
	JLE   rdone

rloop:
	VMOVUPS (SI), Y12
	VMOVUPS 32(SI), Y13
	VBROADCASTSS (R8)(BX*4), Y14
	VFMADD231PS Y12, Y14, Y0
	VFMADD231PS Y13, Y14, Y1
	VBROADCASTSS (R10)(BX*4), Y15
	VFMADD231PS Y12, Y15, Y2
	VFMADD231PS Y13, Y15, Y3
	VBROADCASTSS (R12)(BX*4), Y14
	VFMADD231PS Y12, Y14, Y4
	VFMADD231PS Y13, Y14, Y5
	VBROADCASTSS (R13)(BX*4), Y15
	VFMADD231PS Y12, Y15, Y6
	VFMADD231PS Y13, Y15, Y7
	VBROADCASTSS (DI)(BX*4), Y14
	VFMADD231PS Y12, Y14, Y8
	VFMADD231PS Y13, Y14, Y9
	VBROADCASTSS (DX)(BX*4), Y15
	VFMADD231PS Y12, Y15, Y10
	VFMADD231PS Y13, Y15, Y11
	ADDQ $64, SI
	INCQ BX
	CMPQ BX, CX
	JLT  rloop

rdone:
	MOVQ ep+24(FP), R9
	MOVQ 144(R9), R11

	VBROADCASTSS 0(R9), Y12
	VBROADCASTSS 24(R9), Y13
	VFMADD213PS Y13, Y12, Y0
	VFMADD213PS Y13, Y12, Y1
	VBROADCASTSS 4(R9), Y12
	VBROADCASTSS 28(R9), Y13
	VFMADD213PS Y13, Y12, Y2
	VFMADD213PS Y13, Y12, Y3
	VBROADCASTSS 8(R9), Y12
	VBROADCASTSS 32(R9), Y13
	VFMADD213PS Y13, Y12, Y4
	VFMADD213PS Y13, Y12, Y5
	VBROADCASTSS 12(R9), Y12
	VBROADCASTSS 36(R9), Y13
	VFMADD213PS Y13, Y12, Y6
	VFMADD213PS Y13, Y12, Y7
	VBROADCASTSS 16(R9), Y12
	VBROADCASTSS 40(R9), Y13
	VFMADD213PS Y13, Y12, Y8
	VFMADD213PS Y13, Y12, Y9
	VBROADCASTSS 20(R9), Y12
	VBROADCASTSS 44(R9), Y13
	VFMADD213PS Y13, Y12, Y10
	VFMADD213PS Y13, Y12, Y11

	TESTQ $1, R11
	JZ    rnorelu
	VXORPS Y15, Y15, Y15
	VMAXPS Y15, Y0, Y0
	VMAXPS Y15, Y1, Y1
	VMAXPS Y15, Y2, Y2
	VMAXPS Y15, Y3, Y3
	VMAXPS Y15, Y4, Y4
	VMAXPS Y15, Y5, Y5
	VMAXPS Y15, Y6, Y6
	VMAXPS Y15, Y7, Y7
	VMAXPS Y15, Y8, Y8
	VMAXPS Y15, Y9, Y9
	VMAXPS Y15, Y10, Y10
	VMAXPS Y15, Y11, Y11

rnorelu:
	TESTQ $2, R11
	JZ    rnomul
	MOVQ 96(R9), R10
	VMULPS (R10), Y0, Y0
	VMULPS 32(R10), Y1, Y1
	MOVQ 104(R9), R10
	VMULPS (R10), Y2, Y2
	VMULPS 32(R10), Y3, Y3
	MOVQ 112(R9), R10
	VMULPS (R10), Y4, Y4
	VMULPS 32(R10), Y5, Y5
	MOVQ 120(R9), R10
	VMULPS (R10), Y6, Y6
	VMULPS 32(R10), Y7, Y7
	MOVQ 128(R9), R10
	VMULPS (R10), Y8, Y8
	VMULPS 32(R10), Y9, Y9
	MOVQ 136(R9), R10
	VMULPS (R10), Y10, Y10
	VMULPS 32(R10), Y11, Y11

