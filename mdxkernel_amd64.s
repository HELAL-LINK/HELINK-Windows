	MOVQ 48(R9), R10
	VMOVUPS Y0, (R10)
	VMOVUPS Y1, 32(R10)
	MOVQ 56(R9), R10
	VMOVUPS Y2, (R10)
	VMOVUPS Y3, 32(R10)
	MOVQ 64(R9), R10
	VMOVUPS Y4, (R10)
	VMOVUPS Y5, 32(R10)
	MOVQ 72(R9), R10
	VMOVUPS Y6, (R10)
